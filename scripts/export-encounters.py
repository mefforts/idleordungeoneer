"""Isolate the twelve encounter sprites without changing their source atlas."""
import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'assets/encounters'
source = Image.open(DIRECTORY / 'source.png').convert('RGBA')
rgba = np.asarray(source).copy()
labels, _ = ndimage.label(rgba[:, :, 3] > 80)
counts = np.bincount(labels.ravel())
counts[0] = 0
owners = np.zeros(labels.shape, dtype=np.int16)
slots = {}
slices = ndimage.find_objects(labels)
for label in np.argsort(counts)[-12:]:
    ys, xs = slices[label - 1]
    column = min(3, int((xs.start + xs.stop) / 2 / source.width * 4))
    row = min(2, int((ys.start + ys.stop) / 2 / source.height * 3))
    slot = row * 4 + column
    assert slot not in slots, ('duplicate silhouette', slot)
    slots[slot] = int(label)
    owners[labels == label] = slot + 1
assert set(slots) == set(range(12)), 'Missing encounter silhouette'
distances, indices = ndimage.distance_transform_edt(owners == 0, return_indices=True)
nearest = owners[tuple(indices)]
art, metrics = {}, {}
for row, mechanic in enumerate(['mend', 'fury', 'reflect']):
    for column, zone in enumerate(['overgrowth', 'embervault', 'crypt', 'rift']):
        slot = row * 4 + column
        mask = (nearest == slot + 1) & (distances <= 44) & (rgba[:, :, 3] >= 24)
        ys, xs = np.nonzero(mask)
        box = [int(xs.min()), int(ys.min()), int(xs.max() + 1), int(ys.max() + 1)]
        pixels = rgba[box[1]:box[3], box[0]:box[2]].copy()
        pixels[:, :, 3] = np.where(mask[box[1]:box[3], box[0]:box[2]], pixels[:, :, 3], 0)
        sprite = Image.new('RGBA', (pixels.shape[1] + 12, pixels.shape[0] + 12))
        sprite.paste(Image.fromarray(pixels), (6, 6))
        out = io.BytesIO()
        sprite.save(out, format='WEBP', quality=94, method=6)
        key = zone + '-' + mechanic
        art[key] = {'src': 'data:image/webp;base64,' + base64.b64encode(out.getvalue()).decode(), 'width': sprite.width, 'height': sprite.height}
        metrics[key] = {'source': box, 'width': sprite.width, 'height': sprite.height, 'bytes': len(out.getvalue())}
(ROOT / 'src/encounter-art.js').write_text('/* Generated by scripts/export-encounters.py. */\nconst ENCOUNTER_ART=' + json.dumps(art, separators=(',', ':')) + ';\n')
(DIRECTORY / 'catalog.json').write_text(json.dumps(metrics, indent=2) + '\n')
print('Exported 4 healing totems, 4 power totems and 4 reflect wards.')
