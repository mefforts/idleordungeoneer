"""Isolate painted elite sprites and pack uniformly centered boon medallions."""
from pathlib import Path
from PIL import Image
from scipy import ndimage
import numpy as np
import base64, io, json

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'assets/rare-elites'
art, icons, metrics = {}, {}, {}

def isolate(filename, columns, rows):
    source = Image.open(DIRECTORY / filename).convert('RGBA')
    rgba = np.asarray(source)
    labels, _ = ndimage.label(rgba[:, :, 3] > 128)
    counts = np.bincount(labels.ravel()); counts[0] = 0
    slices, slots = ndimage.find_objects(labels), {}
    owners = np.zeros(labels.shape, dtype=np.int16)
    for label in np.argsort(counts)[-columns * rows:]:
        ys, xs = slices[label - 1]
        col = min(columns - 1, int((xs.start + xs.stop) / 2 / source.width * columns))
        row = min(rows - 1, int((ys.start + ys.stop) / 2 / source.height * rows))
        slot = row * columns + col
        assert slot not in slots, (filename, slot)
        slots[slot] = label
        owners[labels == label] = slot + 1
    assert set(slots) == set(range(columns * rows))
    distance, indices = ndimage.distance_transform_edt(owners == 0, return_indices=True)
    nearest = owners[tuple(indices)]
    result = []
    for slot in range(columns * rows):
        mask = (nearest == slot + 1) & (distance <= 32) & (rgba[:, :, 3] >= 24)
        ys, xs = np.nonzero(mask)
        box = [int(xs.min()), int(ys.min()), int(xs.max() + 1), int(ys.max() + 1)]
        pixels = rgba[box[1]:box[3], box[0]:box[2]].copy()
        pixels[:, :, 3] = np.where(mask[box[1]:box[3], box[0]:box[2]], pixels[:, :, 3], 0)
        result.append((Image.fromarray(pixels), box))
    return result

def pack(image):
    output = io.BytesIO(); image.save(output, 'WEBP', quality=94, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(output.getvalue()).decode(), len(output.getvalue())

for slot, (sprite, box) in enumerate(isolate('creatures.png', 6, 4)):
    key = ['overgrowth', 'embervault', 'crypt', 'rift'][slot // 6] + '-' + str(slot % 6)
    padded = Image.new('RGBA', (sprite.width + 12, sprite.height + 12))
    padded.alpha_composite(sprite, (6, 6))
    uri, size = pack(padded)
    art[key] = {'src': uri, 'width': padded.width, 'height': padded.height}
    metrics[key] = {'source': box, 'width': padded.width, 'height': padded.height, 'bytes': size}

keys = ['codex-rare_elites', 'codex-elite_boon_fervor', 'codex-elite_boon_windstep', 'codex-elite_boon_stoneguard']
for key, (sprite, box) in zip(keys, isolate('medallions.png', 2, 2)):
    sprite.thumbnail((180, 180), Image.Resampling.LANCZOS)
    padded = Image.new('RGBA', (192, 192))
    padded.alpha_composite(sprite, ((192 - sprite.width) // 2, (192 - sprite.height) // 2))
    uri, size = pack(padded); icons[key + '.svg'] = uri
    metrics[key] = {'source': box, 'width': 192, 'height': 192, 'bytes': size}

families = [('overgrowth','shellback',6),('overgrowth','leaf-viper',7),('embervault','coal-drake',6),('embervault','foundry-construct',7),('embervault','ember-moth',8),('embervault','slag-wyrm',9),('crypt','tomb-jackal',6),('crypt','bone-knight',7),('crypt','grave-ooze',8),('crypt','candle-wraith',9),('crypt','grave-fungus',10),('crypt','soul-bat',11),('rift','void-ray',6),('rift','star-golem',7),('rift','astral-urchin',8),('rift','astral-serpent',9),('rift','rift-strider',10),('rift','watcher',11)]
bestiary = {}
for slot, (sprite, box) in enumerate(isolate('depth-expansion.png',6,6)):
    zone, family, variant = families[slot // 2]
    key = zone + '-' + (str(variant) if slot % 2 else family)
    padded = Image.new('RGBA',(sprite.width+12,sprite.height+12)); padded.alpha_composite(sprite,(6,6))
    uri, size = pack(padded)
    record = {'src':uri,'width':padded.width,'height':padded.height}
    (art if slot % 2 else bestiary)[key] = record
    metrics[('elite:' if slot % 2 else 'creature:')+key] = {'source':box,'width':padded.width,'height':padded.height,'bytes':size}
(ROOT / 'src/bestiary-art.js').write_text('/* Generated by scripts/export-rare-elites.py. */\nconst BESTIARY_ART=' + json.dumps(bestiary,separators=(',',':')) + ';\n')

(ROOT / 'src/rare-elite-art.js').write_text('/* Generated by scripts/export-rare-elites.py. */\nconst RARE_ELITE_ART=' + json.dumps(art, separators=(',', ':')) + ';\n')
(ROOT / 'src/elite-boon-icons.json').write_text(json.dumps(icons, separators=(',', ':')) + '\n')
(DIRECTORY / 'metrics.json').write_text(json.dumps(metrics, indent=2) + '\n')
(DIRECTORY / 'catalog.json').write_text(json.dumps({'zoneFloors':[5,10,20,20],'families':[8,10,12,12],'ordinaryCreatureForms':42,'eliteCreatureForms':42,'newOrdinarySprites':18,'eliteSprites':42,'medallions':4,'sourceAtlases':['creatures.png','depth-expansion.png','medallions.png']},indent=2)+'\n')
print('Exported 42 elite creatures, 18 additional ordinary creatures and 4 centered medallions.')
