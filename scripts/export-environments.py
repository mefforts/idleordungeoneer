"""Export isolated game sprites and floor textures from generated source atlases.

Connected silhouettes own their antialiased edge pixels, so adjacent atlas cells
cannot leak into each other's sprites. Source artwork is never overwritten.
"""
import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'assets/environments'
KEYS = {
 'overgrowth': ['twisted-oak','hollow-stump','fallen-log','rooted-menhir','ferns','mushrooms','root-tangle','moss-plinth','moss-beetle','sapling','capling','bramble-hound','root-crawler','root-carpet','fallen-leaves','moss-mosaic'],
 'embervault': ['furnace','coal-cart','iron-pipes','basalt-columns','slag-heap','chimney','foundry-wall','ember-monolith','ash-imp','slag-beetle','soot-wisp','furnace-hound','obsidian-crawler','ash-patch','cooled-slag','foundry-paving'],
 'crypt': ['sarcophagus','mausoleum','dead-tree','grave-cluster','bone-heap','candles','fallen-effigy','soul-urn','bone-thrall','grave-moth','bone-scarab','shroudling','grave-crawler','bone-scatter','funerary-mosaic','grave-mist'],
 'rift': ['crystal-arch','armillary','astral-obelisk','shard-cluster','star-dais','broken-bridge','split-column','moon-marker','shard-crawler','astral-jelly','star-moth','void-hound','rift-wisp','crystal-scatter','star-mosaic','astral-dust']
}
art, metrics = {}, {}


def publish(key, image, source_box):
    out = io.BytesIO()
    image.save(out, format='WEBP', quality=94, method=6)
    art[key] = {'src':'data:image/webp;base64,'+base64.b64encode(out.getvalue()).decode(), 'width':image.width, 'height':image.height}
    metrics[key] = {'source':source_box, 'width':image.width, 'height':image.height, 'bytes':len(out.getvalue())}


for zone, keys in KEYS.items():
    source = Image.open(DIRECTORY / f'depth-{zone}.png').convert('RGBA')
    rgba = np.asarray(source).copy()
    labels, _ = ndimage.label(rgba[:,:,3] > 80)
    counts = np.bincount(labels.ravel()); counts[0] = 0
    largest = np.argsort(counts)[-16:]
    slices = ndimage.find_objects(labels)
    owners = np.zeros(labels.shape, dtype=np.int16)
    slots = {}
    for label in largest:
        ys, xs = slices[label-1]
        column = min(3, int(((xs.start+xs.stop)/2) / source.width * 4))
        row = min(3, int(((ys.start+ys.stop)/2) / source.height * 4))
        slot = row*4+column
        assert slot not in slots, (zone,slot,'two main silhouettes in one cell')
        slots[slot] = int(label)
        owners[labels==label] = slot+1
    assert set(slots)==set(range(16)), (zone,'missing silhouettes')
    distances, indices = ndimage.distance_transform_edt(owners==0, return_indices=True)
    nearest = owners[tuple(indices)]
    for i,key in enumerate(keys):
        mask=(nearest==i+1)&(distances<=64)&(rgba[:,:,3]>=24)
        ys,xs=np.nonzero(mask)
        box=[int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)]
        pixels=rgba[box[1]:box[3],box[0]:box[2]].copy()
        pixels[:,:,3]=np.where(mask[box[1]:box[3],box[0]:box[2]],pixels[:,:,3],0)
        sprite=Image.new('RGBA',(pixels.shape[1]+12,pixels.shape[0]+12))
        sprite.paste(Image.fromarray(pixels),(6,6))
        publish(zone+'-'+key,sprite,box)
    print(zone+': 8 scenery sprites, 5 monsters and 3 ground details')

terrain=Image.open(DIRECTORY/'depth-floors.png').convert('RGB')
for kind,zone in enumerate(KEYS):
    for stage in [2,3]:
        x0=round(kind*terrain.width/4)+5; x1=round((kind+1)*terrain.width/4)-5
        y0=round((stage-2)*terrain.height/2)+5; y1=round((stage-1)*terrain.height/2)-5
        publish(zone+'-floor-'+str(stage),terrain.crop((x0,y0,x1,y1)),[x0,y0,x1,y1])
assert len(art)==72
(ROOT/'src/environment-art.js').write_text('/* Generated by scripts/export-environments.py. */\nconst ENVIRONMENT_ART='+json.dumps(art,separators=(',',':'))+';\n')
(DIRECTORY/'expansion-metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
(DIRECTORY/'expansion-catalog.json').write_text(json.dumps({'zones':KEYS,'newSprites':64,'newTerrainTiles':8,'previousAssets':36,'totalAssets':108},indent=2)+'\n')
print('Exported 72 new art assets; source sheets retained.')
