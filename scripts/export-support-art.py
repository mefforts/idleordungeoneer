"""Export reusable support/channel illustrations and their embedded catalog."""
from pathlib import Path
import base64, json
from support_artwork import illustration, SUPPORT_ROLES, SUPPORT_VARIANTS, TASKS

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/effects/support'
OUT.mkdir(parents=True, exist_ok=True)
art = {}
for family in [*SUPPORT_ROLES, *TASKS]:
    for kind in range(4):
        for variant in range(len(SUPPORT_VARIANTS) if family in SUPPORT_ROLES else 1):
            key = f'{family}-{kind}-{variant}'
            svg = ''.join(illustration(family, kind, variant).splitlines())
            (OUT / (key + '.svg')).write_text(svg + '\n')
            art[key] = 'data:image/svg+xml;base64,' + base64.b64encode(svg.encode()).decode()
frame = {'width': 112, 'height': 124, 'anchorY': 112 / 124}
families = {name: {'role': 'support', 'variants': SUPPORT_VARIANTS} for name in SUPPORT_ROLES}
families.update({name: {'role': 'instrument', 'variants': [{'name': name}]} for name in TASKS})
catalog = {'frame': frame, 'themes': ['overgrowth', 'embervault', 'hollow-crypt', 'astral-rift'], 'families': families, 'files': [key + '.svg' for key in art]}
(OUT / 'catalog.json').write_text(json.dumps(catalog, indent=2) + '\n')
(ROOT / 'src/support-art-assets.js').write_text('/* Generated by npm run art:support. */\nconst SUPPORT_ART=' + json.dumps(art, separators=(',', ':')) + ';\nconst SUPPORT_ART_FRAME=' + json.dumps(frame, separators=(',', ':')) + ';\nconst SUPPORT_ART_META=' + json.dumps(families, separators=(',', ':')) + ';\n')
print(f'Exported {len(art)} support illustrations: 24 totem silhouettes and 16 elite instruments.')
